def build_parser():
    parser = argparse.ArgumentParser(
        prog="odoo-cli.py",
        description="Manage Odoo instances inside the dev Docker container.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=f"""
examples (python3 odoo-cli.py ...):
  start -p myproject -d mydb -i my_module   background instance (agents, scripts)
  restart -u my_module                      after a code change
  stop -p myproject                         end; removes its environment
  workon myproject                          interactive shell; see workon --help
  exec -p myproject -- odoo -d test_db -u my_module --test-enable \\
      --test-tags :MyTest --stop-after-init --no-http    tests
  check -p myproject -i my_module           static check, no DB
  status [--json]                           running instances
  start -d mydb                             'default' instance, port {DEFAULT_PORT}

Run COMMAND --help for details.
""",
    )

    sub = parser.add_subparsers(dest="subcommand", required=True)

    def add_project(p, help_):
        p.add_argument("-p", "--project", metavar="PROJECT", help=help_)

    def add_modules(p):
        p.add_argument(
            "-i", "--install", nargs="+", metavar="MODULE", help="Modules to install"
        )
        p.add_argument(
            "-u", "--update", nargs="+", metavar="MODULE", help="Modules to update"
        )

    # start
    p = sub.add_parser("start", help="Start an Odoo instance in the background")
    add_project(
        p,
        "Instance name; builds its environment from container_configs/PROJECT.txt,"
        " runs [setup] and [requirements] (starts containers if needed)."
        " Omit for the 'default' instance.",
    )
    p.add_argument("-d", "--database", metavar="DB", help="Database to use")
    p.add_argument(
        "-P",
        "--port",
        metavar="PORT",
        type=int,
        help=(
            f"HTTP port inside the container (default: {DEFAULT_PORT} for 'default',"
            f" lowest free of {PORT_POOL.start}–{PORT_POOL.stop - 1} otherwise)"
        ),
    )
    add_modules(p)
    p.set_defaults(func=cmd_start)

