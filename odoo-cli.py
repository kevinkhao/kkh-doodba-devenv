def cmd_exec(args):
    """Run an arbitrary command inside the container; with -p, `odoo` in that
    command uses the instance's addons (ODOO_RC is set; the environment is built
    if missing)."""
    cmd = args.cmd[1:] if args.cmd and args.cmd[0] == "--" else args.cmd
    if not cmd:
        print("ERROR: Provide a command to run.", file=sys.stderr)
        sys.exit(1)
    env = _ensure_instance_env(args.project) if args.project else None
    _exec(cmd, interactive=sys.stdin.isatty(), env=env)


# Bash rc for the `workon` shell. ODOO_RC makes every `odoo`/`click-odoo` use the
# instance's addons. The `odoo()` wrapper gives server runs DEFAULT_FLAGS (before
# the user's, so theirs win), the instance port, a PID file and the instance log,
# so status/logs/stop/restart and Traefik see them. Subcommands (`odoo shell`, ...)
# pass straight through.
_WORKON_RC_TEMPLATE = """[ -f "$HOME/.bashrc" ] && source "$HOME/.bashrc"
export ODOO_RC="__CONF__"
PS1="(__INSTANCE__) $PS1"
odoo() {
    case "${1:-}" in
        server) shift ;;
        "" | -*) ;;
        *) command odoo "$@"; return ;;
    esac
    if [ ! -f "$ODOO_RC" ]; then
        echo "workon: instance environment removed (stop?); exit and rerun workon" >&2
        return 1
    fi
    local _db="" _args=("$@") _i
    for ((_i = 0; _i < ${#_args[@]}; _i++)); do
        case "${_args[$_i]}" in
            -d | --database) _db="${_args[$((_i + 1))]}" ;;
            -d* ) _db="${_args[$_i]#-d}" ;;
            --database=*) _db="${_args[$_i]#--database=}" ;;
        esac
    done
    local _filter=()
    [ -n "$_db" ] && _filter=("--db-filter=^${_db}$")
    # Odoo writes to the instance log; `tail` shows it here without becoming a
    # child of Odoo (which would make Odoo warn about it on shutdown).
    command odoo __DEFAULT_FLAGS__ "${_filter[@]}" "$@" __PORT_FLAG__=__PORT__ \
        > "__LOGFILE__" 2>&1 &
    local _pid=$!
    printf '%s\\n%s\\n%s\\n' "$_pid" "$_db" "__PORT__" > "__PIDFILE__"
    trap 'kill "$_pid" 2>/dev/null' INT
    # Ctrl+C only reaches the foreground `tail`; once it ends, stop Odoo too
    # (no-op if Odoo already exited, e.g. with --stop-after-init).
    tail -n +1 -f --pid="$_pid" "__LOGFILE__"
    kill "$_pid" 2>/dev/null
    wait "$_pid"; local _rc=$?
    trap - INT
    # Only remove the PID file if it is still ours (restart may have replaced it)
    [ "$(sed -n 1p "__PIDFILE__" 2>/dev/null)" = "$_pid" ] && rm -f "__PIDFILE__"
    return $_rc
}
cat << 'EOF'
────────────────────────────────────────────────────────────────────────────
workon __INSTANCE__ → http://__HOSTNAME__   (Odoo is not running yet)

  odoo -d DB -i MODULE    install and serve     Ctrl+C   stop Odoo
  odoo -d DB -u MODULE    update and serve      exit     leave (cleans up)
  odoo shell -d DB        REPL on the same addons

  Details: python3 odoo-cli.py workon --help
────────────────────────────────────────────────────────────────────────────
EOF
"""


def _workon_help():
    """Description for `workon --help` (built from this environment's constants)."""
    dyn = str(TRAEFIK_DYNAMIC_DIR).replace(str(pathlib.Path.home()), "~")
    host = f"PROJECT.{TRAEFIK_BASE_HOSTNAME}"
    return f"""\
Run a project's Odoo by hand and test it in a browser, served by Traefik at
  http://{host}

workon PROJECT:
  1. builds the instance environment from container_configs/PROJECT.txt
     (addons symlinks + odoo.conf), runs [setup] and pip [requirements]
  2. picks a port ({PORT_POOL.start}-{PORT_POOL.stop - 1}) and writes the Traefik route
     {dyn}/{_compose_project()}-PROJECT.yml
  3. opens a bash shell in the odoo container; Odoo is NOT started

In that shell:
  odoo -d DB -i MODULE   install MODULE (DB is created if missing) and serve
  odoo -d DB -u MODULE   update MODULE after code changes and serve
  Ctrl+C                 stop Odoo, keep the shell
  odoo shell -d DB       Python REPL on the same addons
  exit                   leave; removes route + environment unless Odoo runs

While Odoo runs, open http://{host}
(a new DB logs in as admin/admin).
`odoo` there gets the project's addons, the instance port, the dev flags of
`start` (auto-reload, one worker; your own flags win), a PID file and the log
odoo/auto/odoo-PROJECT.log, so from another terminal these work:
  odoo-cli.py status | logs -p PROJECT -f | restart -p PROJECT | stop -p PROJECT

Changed container_configs/PROJECT.txt? `exit` and run workon again.

Traefik prerequisites (once per machine):
  - Traefik v3 on the external Docker network "traefik", HTTP on port 80,
    file provider watching {dyn} (--providers.file.watch=true)
  - this stack's odoo container on that network (devel.yaml does this)
  - {host} resolving to 127.0.0.1 (automatic with
    systemd-resolved or macOS; otherwise workon prints the /etc/hosts line)
  Inspect routes in the Traefik dashboard (http://127.0.0.1:8080 with
  --api.insecure).
"""


def cmd_workon(args):
    """Build a project's instance environment and open an interactive shell in it.

    Nothing is started: the developer runs `odoo ...` by hand in the shell (see
    _WORKON_RC_TEMPLATE for what that shell provides). On exit, the environment
    and route are removed unless Odoo is still running for the instance or
    another workon shell for it is open.
    """
    _setup_project(args.project)
    instance = args.project

    _, _, stored_port = _read_pid_meta(instance)
    if _is_running(instance):
        print(
            f"Note: instance '{instance}' is already running (port {stored_port});"
            " `odoo` here would fail to bind it. `stop` or `restart` it instead."
        )
    port = stored_port or _assign_port(instance)
    hostname = _write_traefik_route(instance, port)
    _check_hosts_entry(hostname)

    rc_file = WORKON_RC.format(instance=instance)
    rc_contents = (
        _WORKON_RC_TEMPLATE.replace("__CONF__", _instance_conf(instance))
        .replace("__DEFAULT_FLAGS__", " ".join(DEFAULT_FLAGS))
        .replace("__PORT_FLAG__", PORT_FLAG)
        .replace("__PORT__", str(port))
        .replace("__PIDFILE__", _pid_file(instance))
        .replace("__LOGFILE__", _log_file(instance))
        .replace("__INSTANCE__", instance)
        .replace("__HOSTNAME__", hostname)
    )
    _exec(["bash", "-c", f"cat > {rc_file}"], input=rc_contents.encode())
    _exec(["bash", "--rcfile", rc_file, "-i"], interactive=True, check=False)

    if _is_running(instance) or instance in _workon_instances():
        return
    _remove_traefik_route(instance)
    _remove_instance_env(instance)
    print(f"workon: cleaned up environment and route for '{instance}'.")


def cmd_check(args):
    """Statically validate modules before booting a database (see the comment
    above _MANIFEST_CHECK_SCRIPT).

    -p selects the addons path (the project's, via a throwaway environment;
    default: the global one). -i selects the modules to check; without it, -p
    checks every module the project provides.
    """
    _require_container()

    roots = list(args.install or [])
    tmp_instance = None
    conf = f"{CONTAINER_AUTO}/odoo.conf"
    if args.project:
        desired, err_collect = _collect_desired(_config_file(args.project))
        if err_collect:
            sys.exit(1)
        roots = roots or sorted(desired)
        tmp_instance = f".check-{os.getpid()}"
        _build_instance_env(tmp_instance, desired)
        conf = _instance_conf(tmp_instance)

    roots = sorted(set(roots))
    if not roots:
        print(
            "ERROR: Provide -i MODULE [MODULE ...] and/or -p PROJECT"
            " (checks every module the project provides)",
            file=sys.stderr,
        )
        sys.exit(1)

    try:
        result = _run_manifest_check(roots, conf)
    finally:
        if tmp_instance:
            _remove_instance_env(tmp_instance)

    if args.json:
        print(json.dumps(result))
    else:
        print(f"Checked {result['closure_size']} module(s) ({len(roots)} requested)\n")

        if result["missing_modules"]:
            print(f"MISSING MODULES ({len(result['missing_modules'])}):")
            for name in result["missing_modules"]:
                print(f"  {name}  — not found on any addons path")
            print()

        if result["missing_python_deps"]:
            total = sum(len(v) for v in result["missing_python_deps"].values())
            print(f"MISSING PYTHON DEPENDENCIES ({total}):")
            for name, errs in sorted(result["missing_python_deps"].items()):
                for err in errs:
                    print(f"  {name}: {err}")
            print()

        if result["conflicts"]:
            print(f"EXCLUDES CONFLICTS ({len(result['conflicts'])}):")
            for a, b in result["conflicts"]:
                print(f"  {a}  ×  {b}")
            print()

        if not (
            result["missing_modules"]
            or result["missing_python_deps"]
            or result["conflicts"]
        ):
            print(
                "OK — no missing modules, missing Python deps, or excludes conflicts."
            )

    if (
        result["missing_modules"]
        or result["missing_python_deps"]
        or result["conflicts"]
    ):
        sys.exit(1)


