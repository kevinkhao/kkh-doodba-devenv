def cmd_start(args):
    if getattr(args, "project", None) and not getattr(args, "_no_setup", False):
        _setup_project(args.project)
    _require_container()

    instance = _instance(args)

    with _instances_lock():
        _prune_stale_traefik_routes(keep=instance)
        if _is_running(instance):
            print(
                f"Odoo instance '{instance}' is already running."
                " Use 'restart' to restart it."
            )
            sys.exit(0)

        db = args.database
        port = getattr(args, "port", None) or _assign_port(instance)
        log_file = _log_file(instance)
        pid_file = _pid_file(instance)

        flags = list(DEFAULT_FLAGS) + [f"{PORT_FLAG}={port}"]
        if _has_instance_env(instance):
            # Refresh against BASE_CONF, which a container restart may have changed.
            _write_instance_conf(instance)
            flags = ["-c", _instance_conf(instance)] + flags
        if db:
            # Serve only this DB, so the instance URL opens it directly instead
            # of the database selector (the db container also creates `devel`).
            flags += ["-d", db, f"--db-filter=^{db}$"]
        if getattr(args, "install", None):
            flags += ["-i", ",".join(args.install)]
        if getattr(args, "update", None):
            flags += ["-u", ",".join(args.update)]

        odoo_cmd = "odoo " + " ".join(flags)
        launch = (
            f"nohup {odoo_cmd} > {log_file} 2>&1 & "
            f"_PID=$! && "
            f'printf "%s\\n%s\\n%s\\n" "$_PID" "{db or ""}" "{port}" > {pid_file} && '
            f"echo \"Odoo instance '{instance}' started (PID $_PID, port {port}). "
            f'Logs: {log_file}"'
        )
        _exec(["bash", "-c", launch])
        hostname = _write_traefik_route(instance, port)
    _check_hosts_entry(hostname)


def cmd_stop(args):
    """Stop the instance and remove its route and environment — unless a
    `workon` shell for it is still open, which keeps both."""
    instance = getattr(args, "project", None) or _auto_detect_instance()
    if not instance:
        sys.exit(1)

    if _is_running(instance):
        _kill_instance(instance)
        print(f"Odoo instance '{instance}' stopped.")
    else:
        print(f"Odoo instance '{instance}' is not running.")

    if instance in _workon_instances():
        print(f"Kept route and environment: a `workon {instance}` shell is open.")
        return
    _remove_traefik_route(instance)
    _remove_instance_env(instance)


def cmd_restart(args):
    """Stop and start an instance. With -p the instance environment is rebuilt
    (like `start -p`); without -p the instance is auto-detected and relaunched
    on its existing environment."""
    explicit_project = getattr(args, "project", None)
    if explicit_project:
        instance = explicit_project
    else:
        instances = _list_instances()
        if len(instances) > 1:
            _print_instances_error(instances)
            sys.exit(1)
        instance = instances[0]["instance"] if instances else "default"
        args.project = instance if instance != "default" else None
        args._no_setup = True

    # Infer -d and --port from the PID file when not given
    _, stored_db, stored_port = _read_pid_meta(instance)
    if not args.database and stored_db:
        args.database = stored_db
        print(f"Using database '{stored_db}' from instance metadata.")
    if not getattr(args, "port", None) and stored_port:
        args.port = stored_port

    if _is_running(instance):
        _kill_instance(instance)
        print("Stopped. Waiting for process to exit...")
        time.sleep(2)

    cmd_start(args)


def cmd_status(args):
    if not _container_running():
        print("Container: not running")
        return
    print("Container: running")

    instance = getattr(args, "project", None)
    use_json = getattr(args, "json", False)

    if instance:
        pid, db, port = _read_pid_meta(instance)
        running = _is_running(instance)
        env = (
            str(_rel(_instance_dir(instance))) if _has_instance_env(instance) else None
        )
        if use_json:
            print(
                json.dumps(
                    {
                        "instance": instance,
                        "pid": pid,
                        "db": db,
                        "port": port,
                        "running": running,
                        "env": env,
                    }
                )
            )
            return
        print(f"Instance:  {instance}")
        print(f"Env:       {env or '— (global odoo.conf)'}")
        if running:
            print(f"Odoo:      running (PID {pid})")
            if db:
                print(f"Database:  {db}")
            if port:
                print(f"Port:      {port}")
                print(f"URL:       http://{_traefik_hostname(instance)}")
                print(f"Direct:    http://127.0.0.1:{_host_port(port)}")
            print(f"Logs:      ./odoo/auto/odoo-{instance}.log")
        else:
            print("Odoo:      not running")
        return

    _prune_stale_traefik_routes()
    instances = _list_instances()
    if use_json:
        print(json.dumps(instances))
        return
    if not instances:
        print("Odoo:      not running")
        return

    col_i = max(len("INSTANCE"), max(len(i["instance"]) for i in instances))
    col_p = max(len("PID"), max(len(str(i["pid"])) for i in instances))
    col_d = max(len("DATABASE"), max(len(i["db"] or "—") for i in instances))
    col_o = len("PORT")
    fmt = f"{{:<{col_i}}}  {{:<{col_p}}}  {{:<{col_d}}}  {{:<{col_o}}}"
    print(fmt.format("INSTANCE", "PID", "DATABASE", "PORT"))
    print(fmt.format("─" * col_i, "─" * col_p, "─" * col_d, "─" * col_o))
    for i in instances:
        print(
            fmt.format(
                i["instance"],
                str(i["pid"]),
                i["db"] or "—",
                str(i["port"]) if i["port"] else "—",
            )
        )


